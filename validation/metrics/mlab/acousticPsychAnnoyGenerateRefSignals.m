% the RefMap project (www.refmap.eu), and is subject to licence as detailed
% in the code repository
% (https://github.com/acoustics-code-salford/refmap-psychoacoustics)
%
% As per the licensing information, please be aware that this code is
% WITHOUT ANY WARRANTY; without even the implied warranty of
% MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
%
% Checked by:
% Date last checked:
%

%% Load path
addpath(genpath(fullfile(pwd)))

%% Input parameters

fs = 44.1e3;  % sampling frequency
dt = 1/fs;  % time step
T = 10;  % total time
N = T*fs;  % total sample length
t = linspace(0, T - dt, N).';  % time vector
f_mod32 = 32;  % modulation frequency
m_mod = 0.98;  % modulation factor
outpath = fullfile("validation",...
                   "metrics", "audio");

%% Generate signals

% signal parameters are assigned according to Section 4.3 Table 4.2
% high-pass white noise (HPR)
% HPR: Butterworth-shaped high-pass, fc = 4 kHz, order n (slope = 6n dB/oct)
hpr = @(n) @(f) 1 ./ sqrt(1 + (4e3 ./ f).^(2*n));
whiteNoiseSig = shapedNoise(T, fs, hpr(2), 999);

% modulation signal
sine_mod_32Hz_40dB = m_mod*sin(2*pi*f_mod32.*t);

% BLR: PSD proportional to f^beta (beta = 1 blue, 2 violet), limited to 20 kHz
blr = @(beta, fs) @(f) (max(f,20)/1e3).^(beta/2) .* (f <= fs/2);
blueNoiseSig = shapedNoise(T, fs, blr(1, fs), 999);

% GVR: attenuation curve
curve = [20, 0; 500, 0; 700, 1; 1000, 2; 2000, 4; 5000, 8; 10000, 12; 20000, 15];
gvr = @(f) 10.^(-interp1(log10(curve(:, 1)), curve(:, 2), ...
                         log10(min(max(f,20),20e3)), 'pchip') / 20);
unifMaskNoise = shapedNoise(T, fs, gvr, 999);

%% Table 4.1 test noises: spectral envelope slope x Butterworth band limits,
% generated by direct FFT shaping of white Gaussian noise.
 
order   = 8;                    % Butterworth order of each band-limiting edge (6*order dB/oct)
fref    = 1e3;                  % reference frequency of the slope (Hz)
fclamp  = 20;                   % slope is held constant below this frequency (avoids LF blow-up)
level   = 20e-6*10^(60/20);     % starting RMS in Pa (60 dB SPL); loudness-match afterwards

% Envelope slope in dB/decade: white 0, pink -10, red -20, blue +20
% (applied to the power spectral density, so amplitude ~ f^(slope/20)).
% fu = lower cutoff (0 -> none), fo = upper cutoff (Inf -> none), both Hz, -3 dB points.
%        no  slope   fu     fo
spec = [  1  -10    180    16e3
          2  -10      0    500
          3  -10      0    1e3
          4  -20    180    16e3
          5    0    500    2e3
          6    0    200    5e3
          7   20     20    20e3
          8    0    4e3    8e3
          9    0    4e3    Inf
         10    0    8e3    Inf
         11  -10     20    20e3
         12    0     20    20e3
         13    0    1e3    Inf
         14    0    2e3    Inf
         15    0    5.6e3  Inf
         16    0    110    210
         17    0    725    885
         18    0    2760   3240
         19    10     20    20e3];

tab4_1Sounds = cell(size(spec,1), 1);

for ii = 1:size(spec,1)
    [slopeDB, fu, fo] = deal(spec(ii,2), spec(ii,3), spec(ii,4));
    gainFun = makeGain(slopeDB, fu, fo, order, fref, fclamp);
 
    x = shapedNoise(T, fs, gainFun, 100 + ii);   % distinct fixed seed per sound
    x = x - mean(x);                            % remove DC
    x = x * level / rms(x);                     % calibrated Pa signal
    tab4_1Sounds{ii} = x;

end

%% Loudness match signals and save as wav files
% (assumes current folder is refmap-psychoacoustics root)

% high-pass noise
% unmodulated signals
whiteUnModLoud = [4.4, 10.5, 22.6];
hprUnMod = zeros(N, length(whiteUnModLoud));
for ii = 1:length(whiteUnModLoud)
    
    hprUnMod(:, ii) = setLoudness(whiteNoiseSig, fs, whiteUnModLoud(ii),...
                                  1, "freeFrontal", "5PcEx",...
                                  "ISO 532-1", false, 0.01, 15);
    filename = "hpassWNoise_4kHz_N" + num2str(round(whiteUnModLoud(ii))) + ".wav";

    % select required bit depth
    if max(abs(hprUnMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), hprUnMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% modulated signals
whiteNoiseSigMod = (1 + sine_mod_32Hz_40dB).*whiteNoiseSig;
whiteModLoud = [4.4, 10.6, 22.8];
hprMod = zeros(N, length(whiteModLoud));
for ii = 1:length(whiteModLoud)
    hprMod(:, ii) = setLoudness(whiteNoiseSigMod, fs, whiteModLoud(ii),...
                                1, "freeFrontal", "5PcEx",...
                                "ISO 532-1", false, 0.01, 15);
    filename = "hpassWNoise_4kHz_N" + num2str(round(whiteModLoud(ii))) + "_mod_" + num2str(f_mod32) + "Hz.wav";

    % select required bit depth
    if max(abs(hprMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), hprMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% blue noise
% unmodulated signals
blueUnModLoud = [4.2, 9.4, 19.9];
blrUnMod = zeros(N, length(blueUnModLoud));
for ii = 1:length(blueUnModLoud)
    blrUnMod(:, ii) = setLoudness(blueNoiseSig, fs, blueUnModLoud(ii),...
                                  1, "freeFrontal", "5PcEx",...
                                  "ISO 532-1", false, 0.01, 15);
    filename = "blueNoise_N" + num2str(round(blueUnModLoud(ii))) + ".wav";

    % select required bit depth
    if max(abs(blrUnMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), blrUnMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% modulated signals
blueNoiseSigMod = (1 + sine_mod_32Hz_40dB).*blueNoiseSig;
blueModLoud = [4.3, 9.5, 20.5];
blrMod = zeros(N, length(blueModLoud));
for ii = 1:length(blueModLoud)
    blrMod(:, ii) = setLoudness(blueNoiseSigMod, fs, blueModLoud(ii),...
                                1, "freeFrontal", "5PcEx",...
                                "ISO 532-1", false, 0.01, 15);
    filename = "blueNoise_N" + num2str(round(blueModLoud(ii))) + "_mod_" + num2str(f_mod32) + "Hz.wav";

    % select required bit depth
    if max(abs(blrMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), blrMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% uniform masking noise
% unmodulated signals
unifMaskUnModLoud = [4.5, 10.8, 23];
gvrUnMod = zeros(N, length(unifMaskUnModLoud));
for ii = 1:length(unifMaskUnModLoud)
    gvrUnMod(:, ii) = setLoudness(unifMaskNoise, fs, unifMaskUnModLoud(ii),...
                                  1, "freeFrontal", "5PcEx",...
                                  "ISO 532-1", false, 0.01, 15);
    filename = "unifMaskNoise_N" + num2str(round(unifMaskUnModLoud(ii))) + ".wav";

    % select required bit depth
    if max(abs(gvrUnMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), gvrUnMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% modulated signals
unifMaskNoiseSigMod = (1 + sine_mod_32Hz_40dB).*unifMaskNoise;
unifMaskModLoud = [4.6, 10.9, 22.8];
gvrMod = zeros(N, length(unifMaskModLoud));
for ii = 1:length(unifMaskModLoud)
    gvrMod(:, ii) = setLoudness(unifMaskNoiseSigMod, fs, unifMaskModLoud(ii),...
                                1, "freeFrontal", "5PcEx",...
                                "ISO 532-1", false, 0.01, 15);
    filename = "unifMaskNoise_N" + num2str(round(unifMaskModLoud(ii))) + "_mod_" + num2str(f_mod32) + "Hz.wav";

    % select required bit depth
    if max(abs(gvrMod(:, ii))) > 1
        bitsRequired = 32;
    else
        bitsRequired = 24;
    end

    audiowrite(fullfile(outpath, filename), gvrMod(:, ii), fs,...
               "BitsPerSample", bitsRequired)
end

% table 4.2 signals
tab4_1Loud = 12; %[6, 12, 18];
tab4_1 = zeros(N, length(tab4_1Sounds), length(tab4_1Loud));
for jj = 1:length(tab4_1Loud)
    for ii = 1:length(tab4_1Sounds)
        tab4_1(:, ii, jj) = setLoudness(tab4_1Sounds{ii}, fs, tab4_1Loud(jj),...
                                    1, "freeFrontal", "5PcEx",...
                                    "ISO 532-1 S", false, 0.01, 15);
        filename = "tab_4_1_sound" + num2str(spec(ii, 1)) + "_" + num2str(round(tab4_1Loud(jj))) + "sone" + ".wav";

        % select required bit depth
        if max(abs(tab4_1(:, ii, jj))) > 1
            bitsRequired = 32;
        else
            bitsRequired = 24;
        end
    
        audiowrite(fullfile(outpath, filename), tab4_1(:, ii, jj), fs,...
                   "BitsPerSample", bitsRequired)
    end
end

%%
function x = shapedNoise(T, fs, gainFun, seed)
% White Gaussian noise multiplied by gainFun(f) in the frequency domain.
    if nargin > 3
        rng(seed);
    end
    N = round(T*fs);
    X = fft(randn(N, 1));
    f = (0:N - 1)' * fs/N;  f = min(f, fs - f);      % symmetric frequency axis
    x = real(ifft(X .* gainFun(max(f, 1e-3))));
end

function g = makeGain(slopeDB, fu, fo, n, fref, fclamp)
% Amplitude gain = power-law slope x Butterworth high-pass (fu) x low-pass (fo).
    slope = @(f) (max(f, fclamp)/fref).^(slopeDB/20);
    if fu > 0,        hp = @(f) 1 ./ sqrt(1 + (fu ./ f).^(2*n));
    else,             hp = @(f) ones(size(f)); end
    if isfinite(fo),  lp = @(f) 1 ./ sqrt(1 + (f ./ fo).^(2*n));
    else,             lp = @(f) ones(size(f)); end
    g = @(f) slope(f) .* hp(f) .* lp(f);
end

end
% end of function